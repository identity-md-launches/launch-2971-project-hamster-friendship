// Package the accepted engine for the server. No second game implementation:
// only a headless entry/serialization bridge is injected into the same closure.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const game=await readFile('src/game.js','utf8'),rules=await readFile('src/rules.js','utf8');
const bridge=`
  window.replayEngine = {
    async init(config, state) {
      await startGame(config.map, true);
      if (state) {
        game=state.game; player=state.player; enemies=state.enemies; boss=state.boss;
        pickups=state.pickups; shots=state.shots; things=state.things; burns=state.burns;
        attackId=state.attackId; defeatedCount=state.defeatedCount; mapFinished=state.mapFinished;
      }
    },
    step(input) {
      if (game.state !== 'playing' || input.frame !== game.frames) throw Error('Input does not follow the saved run.');
      var names=['left','right','jump','throw','interact','slot1','slot2','slot3'];
      held={}; pressed={}; names.forEach(function(name,i){held[name]=!!(input.held & (1<<i));pressed[name]=!!(input.pressed & (1<<i));});
      movement.pointer=input.touch ? 1 : null; movement.x=input.x; movement.y=input.y; movement.amount=Math.hypot(input.x,input.y);
      if (input.weapon !== player.weapon) {
        if (player.weapons.indexOf(input.weapon) === -1) throw Error('Collect this weapon before selecting it.');
        player.weapon=input.weapon;
      }
      tick(true);
      // Dialogue pauses active physics. Complete its existing callbacks before
      // the next active input; reading speed cannot earn rewards or move Chang.
      while(game.state==='dialogue') advanceDialogue();
      fx=[];
    },
    finish() { if(boss.state!=='defeated') throw Error('Defeat the boss before finishing.'); finishRun(); },
    snapshot() { return JSON.parse(JSON.stringify({game:game,player:player,enemies:enemies,boss:boss,pickups:pickups,shots:shots,things:things,burns:burns,attackId:attackId,defeatedCount:defeatedCount,mapFinished:mapFinished})); }
  };
`;
const marker='  // Title state uses a fresh world';
if(!game.includes(marker))throw Error('Engine bridge marker missing');
const output=`// Generated by scripts/prepare-replay.mjs from src/game.js and src/rules.js.\n// Trusted server source, never evaluated from a request. Rebuild after engine edits.\nexport const engineHash = '${createHash('sha256').update(game+rules).digest('hex')}';\nexport function loadEngine(window, document, performance, Event) {\nconst globalThis=window;\n${rules}\n${game.replace(marker,bridge+'\n'+marker).replace('void startGame(mapNumber + 1, true);', '// Replay persists one run; the browser starts the next map after acknowledgement.')}\n}\n`;
const path='supabase/functions/_shared/engine.js';
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==output)throw Error('Server engine differs from current source. Run node scripts/prepare-replay.mjs.');console.log('Replay engine matches the shipped source.');}
else {await writeFile(path,output);console.log('Prepared server replay engine.');}
